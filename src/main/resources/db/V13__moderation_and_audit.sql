ALTER TABLE post_comments ADD COLUMN hidden BOOLEAN NOT NULL DEFAULT FALSE, ADD COLUMN deleted BOOLEAN NOT NULL DEFAULT FALSE;
CREATE TABLE audit_events (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, actor_id BIGINT NOT NULL, action VARCHAR(60) NOT NULL,
 target_type VARCHAR(30) NOT NULL, target_id BIGINT NOT NULL, reason VARCHAR(500) NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 CONSTRAINT fk_audit_actor FOREIGN KEY(actor_id) REFERENCES users(id), INDEX idx_audit_created(created_at)
);
CREATE TABLE content_reports (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, reporter_id BIGINT NOT NULL, target_type VARCHAR(20) NOT NULL,
 target_id BIGINT NOT NULL, reason VARCHAR(500) NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
 reviewed_by BIGINT NULL, review_reason VARCHAR(500) NULL, created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 reviewed_at DATETIME(6) NULL, UNIQUE KEY uq_report(reporter_id,target_type,target_id),
 FOREIGN KEY(reporter_id) REFERENCES users(id), FOREIGN KEY(reviewed_by) REFERENCES users(id)
);
